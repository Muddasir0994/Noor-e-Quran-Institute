/** Number of quotes shown per day. */
export const QUOTES_PER_DAY = 10;

/** Simple string hash (FNV-1a) used to seed the daily shuffle. */
function hashDateString(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

/** Deterministic PRNG (mulberry32) seeded from the date hash. */
function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function seededShuffle<T>(items: readonly T[], seed: number): T[] {
  const arr = [...items];
  const rand = mulberry32(seed);
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/** Local calendar date as YYYY-MM-DD (visitor's own day). */
export function todayKey(now: Date = new Date()): string {
  const y = now.getFullYear();
  const m = String(now.getMonth() + 1).padStart(2, '0');
  const d = String(now.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

/**
 * Deterministically picks QUOTES_PER_DAY quotes for the given date.
 * Every visitor sees the same 10 quotes on the same calendar day;
 * the set changes the next day.
 */
export function getTodaysQuotes(now: Date = new Date()): DailyQuote[] {
  const seed = hashDateString(todayKey(now));
  return seededShuffle(DAILY_QUOTES, seed).slice(0, QUOTES_PER_DAY);
}

/**
 * Picks one random quote from today's 10.
 * Call once per page load — every refresh shows a (possibly) different quote.
 */
export function getRandomQuote(quotes: DailyQuote[] = getTodaysQuotes()): DailyQuote {
  return quotes[Math.floor(Math.random() * quotes.length)];
}
